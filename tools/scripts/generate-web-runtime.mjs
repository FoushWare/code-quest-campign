/*
  tools/scripts/generate-web-runtime.mjs

  Small helper that writes `runtime.generated.ts` into each web app/MFE.
  - This centralizes environment values (phase, serviceMode, and apiBaseUrls)
    so dev servers and builds read consistent configuration.
  - Usage: set `CODE_QUEST_APP_PHASE` and `CODE_QUEST_SERVICE_MODE` env vars,
    then run `node tools/scripts/generate-web-runtime.mjs` or `npm run prepare:web-runtime`.

  Important: runtime.generated.ts is a generated artifact — do not hand-edit it.
*/

import { mkdirSync, writeFileSync, readFileSync, existsSync } from 'fs';
import { resolve } from 'path';

// Determine environment name (development|production|etc.)
const envName = process.env.CODE_QUEST_ENV ?? process.env.NODE_ENV ?? 'development';

// Parse a simple .env file into key/value pairs (no quoting handling required for our use).
function parseDotEnv(path) {
  const out = {};
  if (!existsSync(path)) return out;
  const raw = String(readFileSync(path, { encoding: 'utf8' }));
  for (const line of raw.split(/\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const idx = trimmed.indexOf('=');
    if (idx === -1) continue;
    const key = trimmed.slice(0, idx).trim();
    const val = trimmed.slice(idx + 1).trim();
    out[key] = val;
  }
  return out;
}

// Load .env.<envName> if present (workspace root)
const workspaceRoot = process.cwd();
const dotEnvPath = resolve(workspaceRoot, `.env.${envName}`);
const fileEnv = parseDotEnv(dotEnvPath);

// Merge environment variables: file values are defaults, explicit process.env overrides them
const mergedEnv = { ...fileEnv, ...process.env };

const phase = mergedEnv.CODE_QUEST_APP_PHASE ?? 'mock';
const serviceMode = mergedEnv.CODE_QUEST_SERVICE_MODE ?? 'mock';

// Allow overriding service endpoints via env vars (AUTH_API, CONTENT_API, ...)
const apiBaseUrls = {
  auth: mergedEnv.AUTH_API ?? 'http://localhost:8081',
  content: mergedEnv.CONTENT_API ?? 'http://localhost:8082',
  gamification: mergedEnv.GAMIFICATION_API ?? 'http://localhost:8083',
  leaderboard: mergedEnv.LEADERBOARD_API ?? 'http://localhost:8084',
  spacedRepetition: mergedEnv.SPACED_REPETITION_API ?? 'http://localhost:8085',
};

// The list of surfaces (hosts and MFEs) to generate runtime files for.
// Keep this in sync with apps/web/* folders.
const surfaces = [
  { surface: 'shell', appPath: 'shell', containerRole: 'host' },
  { surface: 'website', appPath: 'website', containerRole: 'standalone' },
  { surface: 'admin', appPath: 'admin', containerRole: 'standalone' },
  { surface: 'website-learning-path', appPath: 'website/learning-path', containerRole: 'microfrontend' },
  { surface: 'website-lessons', appPath: 'website/lessons', containerRole: 'microfrontend' },
  { surface: 'website-hearts-gems', appPath: 'website/hearts-gems', containerRole: 'microfrontend' },
  { surface: 'website-league-social', appPath: 'website/league-social', containerRole: 'microfrontend' },
  { surface: 'website-profile-settings', appPath: 'website/profile-settings', containerRole: 'microfrontend' },
  { surface: 'admin-users', appPath: 'admin/users', containerRole: 'microfrontend' },
  { surface: 'admin-moderation', appPath: 'admin/moderation', containerRole: 'microfrontend' },
  { surface: 'admin-analytics', appPath: 'admin/analytics', containerRole: 'microfrontend' },
  { surface: 'admin-content-editor', appPath: 'admin/content-editor', containerRole: 'microfrontend' },
];

for (const { surface, appPath, containerRole } of surfaces) {
  const filePath = resolve(workspaceRoot, `apps/web/${appPath}/src/runtime.generated.ts`);
  mkdirSync(resolve(filePath, '..'), { recursive: true });

  const content = `// Generated by tools/scripts/generate-web-runtime.mjs (env: ${envName})\nexport const webRuntime = ${JSON.stringify(
    {
      surface,
      containerRole,
      phase,
      serviceMode,
      apiBaseUrls,
    },
    null,
    2,
  )} as const;\n`;

  writeFileSync(filePath, content);
}
